#Shaft Design assistant 
#Assuming shaft is solid, circular, and subjected to pure tension made up of steel
import math
allowable_shear_stress = 250 #in MPa

def torque_calc(): #calculation of torque generated by shaft
    P = float(input("Enter the power generated by motor in kW: "))
    N = int(input("Enter the speed of the shaft in RPM: "))
    if P<=0 or N<=0:
        print("Error: Power and RPM must be positive ")
        return None
    T = (9550*P)/N
    return T#in N-m.

def dia_calc(T):
    d = ((16*T*1000)/(math.pi*allowable_shear_stress))**(1/3)
    return d

def act_shear_calc(T,d):#actual shear stress calculation
    act_shear_stress = (16*T*1000)/(math.pi*d**3) #in N/mm^2
    return act_shear_stress

def FOS(allowable_shear_stress, Shear_actual):
    Shear_actual = act_shear_calc()
    if Shear_actual <=0:
        return None
    fos = allowable_shear_stress/(Shear_actual)
    return fos



T = torque_calc()#Called torque calculation function
if T is not None:
    d = dia_calc(T)#Called diameter calculation function

print("="*15, "SHAFT DESIGN ASSISTANT", "="*15)
print(f"Torque transmitted: {T:.3f} N-m.")
print(f"Allowable shear stress {allowable_shear_stress}Mpa.")
print(f"Minimum shaft diameter: {d:.3f}mm.")
print(f"Actual shear stress: {act_shear_calc(T):.3f}Pa.")
print(f"Factor of safety: {FOS():.3f}")
